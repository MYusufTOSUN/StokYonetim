CREATE OR REPLACE FUNCTION       CARI_TOPLAM_SIPARIS (
  P_CARI_ID IN NUMBER
) RETURN NUMBER
IS
  P_TOPLAM_MIKTAR NUMBER(10,2);
BEGIN
  SELECT NVL((
  SELECT NVL(SUM(MIKTAR), 0)
  FROM SIPARIS_DOSYA
  WHERE CARI_ID = P_CARI_ID),0)   INTO P_TOPLAM_MIKTAR FROM DUAL;
  RETURN NVL(P_TOPLAM_MIKTAR,0);
END;
