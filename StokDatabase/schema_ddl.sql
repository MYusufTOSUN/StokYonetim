CREATE OR REPLACE PROCEDURE       SIPARIS_EKLE (
  P_ISLEM_TURU     IN CHAR,
  P_SIPARIS_ID     IN NUMBER,
  P_CARI_ID        IN NUMBER,
  P_BIRIM          IN VARCHAR2,
  P_STOK_ID        IN NUMBER,
  P_MIKTAR         IN NUMBER,
  P_SIPARIS_TARIHI IN DATE,
  P_SIPARIS_TUR    IN CHAR
)
IS
BEGIN
  IF P_ISLEM_TURU NOT IN ('I', 'U') THEN
    RAISE_APPLICATION_ERROR(-20001, 'P_ISLEM_TURU sadece ''I'' (INSERT) veya ''U'' (UPDATE) olabilir.');
  END IF;

  IF UPPER(P_SIPARIS_TUR) NOT IN ('A', 'V') THEN
    RAISE_APPLICATION_ERROR(-20002, 'P_SIPARIS_TUR sadece ''A'' (Al m) veya ''V'' (Verilen) olabilir.');
  END IF;

  IF P_ISLEM_TURU = 'I' THEN
    INSERT INTO YUSUF.SIPARIS_DOSYA (
      CARI_ID, BIRIM, STOK_ID, MIKTAR, SIPARIS_TARIHI, SIPARIS_TUR
    ) VALUES (
      P_CARI_ID, P_BIRIM, P_STOK_ID, P_MIKTAR, P_SIPARIS_TARIHI, UPPER(P_SIPARIS_TUR)
    );

  ELSIF P_ISLEM_TURU = 'U' THEN
    UPDATE YUSUF.SIPARIS_DOSYA
    SET
      CARI_ID        = P_CARI_ID,
      BIRIM          = P_BIRIM,
      STOK_ID        = P_STOK_ID,
      MIKTAR         = P_MIKTAR,
      SIPARIS_TARIHI = P_SIPARIS_TARIHI,
      SIPARIS_TUR    = UPPER(P_SIPARIS_TUR)
    WHERE SIPARIS_ID = P_SIPARIS_ID;
  END IF;
END;
/

SHOW ERRORS;


CREATE OR REPLACE PROCEDURE       ESITLE_STOK_MIKTAR
IS
BEGIN
  MERGE INTO KART_STOK KS
  USING (
    SELECT
      KS.STOK_ID AS STOK_ID,
      NVL(SD.ALINAN, 0) AS ALINAN,
      NVL(SD.VERILEN, 0) AS VERILEN
    FROM KART_STOK KS
    LEFT JOIN (
      SELECT
        STOK_ID,
        SUM(CASE WHEN SIPARIS_TUR = 'A' THEN MIKTAR ELSE 0 END) AS ALINAN,
        SUM(CASE WHEN SIPARIS_TUR = 'V' THEN MIKTAR ELSE 0 END) AS VERILEN
      FROM SIPARIS_DOSYA
      GROUP BY STOK_ID
    ) SD
    ON KS.STOK_ID = SD.STOK_ID
  ) SD
  ON (KS.STOK_ID = SD.STOK_ID)
  WHEN MATCHED THEN
    UPDATE SET
      KS.ALINAN_SIPARIS_MIKTARI  = SD.ALINAN,
      KS.VERILEN_SIPARIS_MIKTARI = SD.VERILEN;
END ESITLE_STOK_MIKTAR;
/

