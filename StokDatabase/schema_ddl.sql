CREATE OR REPLACE TRIGGER SIPARIS_SENKRON
AFTER INSERT OR DELETE ON SIPARIS_DOSYA FOR EACH ROW
BEGIN

  IF INSERTING THEN
    IF :NEW.SIPARIS_TUR = 'A' THEN
      UPDATE KART_STOK
      SET ALINAN_SIPARIS_MIKTARI = ALINAN_SIPARIS_MIKTARI + :NEW.MIKTAR
      WHERE STOK_ID = :NEW.STOK_ID;
    ELSIF :NEW.SIPARIS_TUR = 'V' THEN
      UPDATE KART_STOK
      SET VERILEN_SIPARIS_MIKTARI = VERILEN_SIPARIS_MIKTARI + :NEW.MIKTAR
      WHERE STOK_ID = :NEW.STOK_ID;
    END IF;
  ELSIF DELETING THEN
    IF :OLD.SIPARIS_TUR = 'A' THEN
      UPDATE KART_STOK
      SET ALINAN_SIPARIS_MIKTARI = ALINAN_SIPARIS_MIKTARI - :OLD.MIKTAR
      WHERE STOK_ID = :OLD.STOK_ID;
    ELSIF :OLD.SIPARIS_TUR = 'V' THEN
      UPDATE KART_STOK
      SET VERILEN_SIPARIS_MIKTARI = VERILEN_SIPARIS_MIKTARI - :OLD.MIKTAR
      WHERE STOK_ID = :OLD.STOK_ID;
    END IF;
  ELSIF UPDATING THEN
    IF :OLD.SIPARIS_TUR = 'A' THEN
      UPDATE KART_STOK
      SET ALINAN_SIPARIS_MIKTARI = ALINAN_SIPARIS_MIKTARI - :OLD.MIKTAR + :NEW.MIKTAR
      
      WHERE STOK_ID = :OLD.STOK_ID;
    ELSIF :OLD.SIPARIS_TUR = 'V' THEN
      UPDATE KART_STOK
      SET VERILEN_SIPARIS_MIKTARI = VERILEN_SIPARIS_MIKTARI - :OLD.MIKTAR + :NEW.MIKTAR
      WHERE STOK_ID = :OLD.STOK_ID;
    END IF;  
  END IF;
END;
/
SHOW ERRORS;


