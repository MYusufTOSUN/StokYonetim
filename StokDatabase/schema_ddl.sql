CREATE OR REPLACE VIEW VW_STOK_TOPLAM_SIPARIS
AS 
SELECT 
  ST.STOK_AD,
  NVL(SUM(S.MIKTAR), 0) AS TOPLAM
FROM KART_STOK ST
LEFT JOIN SIPARIS_DOSYA S ON ST.STOK_ID = S.STOK_ID
GROUP BY ST.STOK_AD;


CREATE OR REPLACE VIEW VW_EKSI_STOKLAR
AS 
SELECT 
  ST.STOK_AD,
  SUM(CASE WHEN S.SIPARIS_TUR = 'V' THEN S.MIKTAR ELSE 0 END) -
  SUM(CASE WHEN S.SIPARIS_TUR = 'A' THEN S.MIKTAR ELSE 0 END) AS NET_MIKTAR
FROM KART_STOK ST
LEFT JOIN SIPARIS_DOSYA S ON S.STOK_ID = ST.STOK_ID
GROUP BY ST.STOK_AD
HAVING (
  SUM(CASE WHEN S.SIPARIS_TUR = 'V' THEN S.MIKTAR ELSE 0 END) -
  SUM(CASE WHEN S.SIPARIS_TUR = 'A' THEN S.MIKTAR ELSE 0 END)
) < 0;


